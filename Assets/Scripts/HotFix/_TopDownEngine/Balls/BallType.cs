namespace MoreMountains
{
    public enum BallType
    {
        Normal,

        #region 元素球

        //激光
        LaserBeam, //每次撞击会产生一道随机方向的激光束打击
        LaserBullet, //每次撞击会发射一枚激光子弹，穿透敌人，碰到障碍即销毁
        //雷电
        LightningStrike, //对场上1名敌人造成闪电打击
        ElectricityStrike, //对附近1名敌人造成电流打击
        Electrified, //对撞击的敌人施加1层感电，持续3秒，每次撞击特效会引爆一次感电伤害
        //冰
        IceFreeze, //对撞击的敌人施加0.5秒的冰冻
        //岩
        RockQuake, //每次撞击会造成一次方形地震伤害
        RockSplash, //对撞击的敌人后方扇形区域造成溅射伤害，伤害为本次撞击伤害的30%
        RockSplit, //每次撞击会向随机方向分裂出1个岩石块，命中敌人1次即销毁
        //毒
        PoisonBurning, //每次撞击会施加1层中毒，最多3层，每层造成每秒造成5点伤害
        PoisonSplatter, //每次撞击溅射毒液落到附近地上，形成圆形区域，敌人在毒液区域上受到减速和和每秒1层的中毒效果
        //飞弹
        Missile, //每次撞击会从玩家身后发射一道轨迹子弹在0.75秒后命中敌人
        PeriodicMissile, //每飞行2米会发射一道轨迹子弹在0.75秒后命中敌人
        //火
        FireBurning, //每次撞击会施加1层灼烧，最多3层，每层造成每秒造成5点伤害
        FireExplode, //每次撞击会造成一次圆形火焰爆炸伤害
        //风
        Wind, //可以穿透敌人
        WindBreeze, //可以穿透敌人，对命中的敌人造成轻微击退，并减速20%，持续2秒
        WindStorm, //可以穿透敌人，会把附近的敌人不断拉向旋涡中心
        //沙
        Sand, //每次撞击特效施加1层[沙环]，2层会引爆造成30点真实伤害
        //光明
        Light, //每次撞击会降低敌人2点护甲
        //黑暗
        Dark, //每次撞击会降低敌人2点魔抗
        //金属
        Metal, //速度慢，撞击伤害高，撞击如果摧毁砖块后则不会反弹
        //分裂
        Fission, //每次撞击有几率复制出一个球
        //创造
        Obstacle, //首次撞击会在原地创建一个障碍物，存活5秒

        #endregion


        #region 融合球

        #endregion
